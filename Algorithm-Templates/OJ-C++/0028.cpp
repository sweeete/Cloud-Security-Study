#include <iostream> // 引入标准输入输出流库，用于控制台输入输出 (cin, cout)
#include <vector>   // 引入动态数组 vector 容器头文件，用于存储输入的数字序列

using namespace std; // 使用标准命名空间 std，避免后续调用标准库组件时重复书写 std::

/**
 * 计算最少需要补齐（添加）多少个正整数，使得 [1, n] 区间内的所有数字都能由 nums 中若干元素的和表示
 * @param nums 初始给定的按升序排列的正整数数组
 * @param n 需要覆盖的目标最大正整数上限
 * @return 最少需要补充的数字个数
 */
int minPatches(const vector<int>& nums, long long n) { // 定义按要求补齐数组的贪心算法函数
    int patches = 0;    // 声明并初始化计数器 patches 为 0，用于记录当前补充添加的数字个数
    long long x = 1;    // 声明变量 x 表示当前尚未能表示的最小正整数（即当前能覆盖区间 [1, x - 1]），用 long long 防止翻倍时溢出
    int i = 0;          // 声明指针 i 并初始化为 0，用于按顺序遍历 nums 数组中的每一个元素
    int m = nums.size(); // 获取输入数组 nums 的实际元素个数 m

    // 只要当前能覆盖的最大范围 x - 1 还没达到目标 n（即 x <= n），就需要继续扩展覆盖范围
    while (x <= n) { // 进入循环校验：当尚缺失的最小正整数 x 处于目标范围 [1, n] 内时继续处理
        // 如果数组中还有未处理的元素，且该元素小于等于当前缺失的最小值 x
        if (i < m && nums[i] <= x) { // 边界与数值判断：已有数组元素 nums[i] 可以无缝联结并扩展覆盖范围
            x += nums[i]; // 利用已有元素 nums[i]，将能够覆盖的区间从 [1, x - 1] 扩展到 [1, x + nums[i] - 1]
            i++;          // 当前数组元素已被顺利利用，指针 i 后移指向 nums 的下一个元素
        } 
        // 若 nums 中无可用元素，或 nums[i] > x（出现断点，当前数组元素过大无法填补 x 的空缺）
        else { // 贪心策略选择：主动补充填补数字 x 自身，这是能扩展覆盖范围的最大且最有效数值
            x += x;    // 补充数字 x 后，覆盖范围从 [1, x - 1] 翻倍扩充到 [1, 2 * x - 1]（即新缺失值为 2 * x）
            patches++; // 成功补充了一个新的数字 x，补齐计数器 patches 加 1
        } // 结束分支逻辑
    } // 结束 while 扩展覆盖范围循环

    return patches; // 返回最终累加计算出的最少补充数字个数
} // 结束 minPatches 函数

int main() { // 程序的主入口函数
    // 提升标准输入输出流（I/O）的执行效率
    ios::sync_with_stdio(false); // 取消 C++ 标准流与 C 语言标准输入输出流的同步，加速数据读取
    cin.tie(nullptr);            // 解绑 cin 与 cout 的关联，避免每次 cin 操作前自动刷新缓冲输出

    int m; // 声明变量 m，用于存储输入的数组 nums 的元素数量
    if (cin >> m) { // 从标准输入中读取数组长度 m，若读取成功则执行内部代码块
        vector<int> nums(m); // 初始化大小为 m 的整型向量 nums，用于存放输入的数组元素
        for (int i = 0; i < m; ++i) { // 循环 m 次，依次读取输入的每一个数组元素
            cin >> nums[i]; // 读取单个数存入数组 nums 的第 i 个位置
        } // 结束数组读入循环

        long long n; // 声明变量 n，用于存储目标覆盖上限数字（数值可能很大）
        cin >> n;    // 从标准输入中读取目标上限数值 n

        cout << minPatches(nums, n) << "\n"; // 调用 minPatches 计算最少补齐数并输出结果，输出换行符
    } // 结束输入校验与处理分支

    return 0; // 程序正常运行完毕，向操作系统返回状态码 0
} // 结束 main 函数