#include <iostream> // 引入标准输入输出流头文件，提供 cin 和 cout 对象进行控制台交互
#include <vector>   // 引入动态数组 vector 容器头文件，用于构建二维矩阵 grid

using namespace std; // 使用标准命名空间 std，后续可以直接写 vector、cin、cout 等而无需 std:: 前缀

/**
 * 计算翻转矩阵后的最大得分（重构矩阵转十进制求和）
 * @param grid 二维 0/1 矩阵引用
 * @return 经过最优行列翻转后的总得分
 */
int matrixScore(vector<vector<int>>& grid) { // 定义矩阵得分计算函数，采用引用传递以避免拷贝开销
    int m = grid.size();    // 获取矩阵的行数 m
    int n = grid[0].size(); // 获取矩阵的列数 n（假设矩阵非空且每行列数相同）

    // ==========================================
    // 步骤 1：按行处理——检查每行的第一个数字（第 0 列，最高位 MSB）
    // 若首位是 0，则翻转整行，确保最高位（第 0 列）全为 1（因为最高位为 1 收益大于后续所有低位全为 1 的和）
    // ==========================================
    for (int i = 0; i < m; ++i) { // 遍历矩阵的每一行（从第 0 行到第 m-1 行）
        if (grid[i][0] == 0) { // 判断当前行第 0 列（最高位）是否为 0
            for (int j = 0; j < n; ++j) { // 如果最高位为 0，遍历当前行的每一列元素
                grid[i][j] ^= 1; // 使用异或运算符 ^= 1 实现按位翻转：0 变成 1，1 变成 0
            } // 结束当前行的翻转循环
        } // 结束 if 判断
    } // 结束行处理循环

    // ==========================================
    // 步骤 2：按列处理——遍历第 1 列到第 n - 1 列
    // 若某列中 0 的数量多于 1 的数量，则翻转整列（尽可能让每一列中 1 的数量更多）
    // ==========================================
    for (int j = 1; j < n; ++j) { // 遍历除最高位以外的每一列（从第 1 列到第 n-1 列）
        int zeroCount = 0; // 声明并初始化计数器，用于统计当前列中 0 的个数
        for (int i = 0; i < m; ++i) { // 遍历当前列中的每一行元素
            if (grid[i][j] == 0) { // 如果当前行、当前列位置的元素为 0
                zeroCount++; // 0 的数量计数器加 1
            } // 结束 if 计数判断
        } // 结束当前列统计循环

        // 如果 0 的数量超过半数（即 0 的数量 zeroCount 大于 1 的数量 m - zeroCount），翻转该列
        if (zeroCount > m - zeroCount) { // 比较当前列中 0 和 1 的相对数量
            for (int i = 0; i < m; ++i) { // 遍历当前列的每一行
                grid[i][j] ^= 1; // 异或 1 翻转整列：0 变 1，1 变 0，提升当前列 1 的占比
            } // 结束整列翻转循环
        } // 结束翻转条件判断
    } // 结束列处理循环

    // ==========================================
    // 步骤 3：计算最终矩阵按二进制转换后的总得分
    // ==========================================
    int totalScore = 0; // 声明并初始化总得分变量为 0
    for (int i = 0; i < m; ++i) { // 遍历矩阵的每一行
        int rowValue = 0; // 声明并初始化当前行转换后的十进制数值为 0
        for (int j = 0; j < n; ++j) { // 从高位到低位顺序遍历当前行的每一列
            // 左移一位（相当于乘以 2）并将当前位的 0/1 加进来，高效把二进制转为十进制
            rowValue = (rowValue << 1) + grid[i][j]; // 位运算：左移一位并按位累加当前列的值
        } // 结束当前行二进制转十进制循环
        totalScore += rowValue; // 将当前行转换得出的十进制数值累加到总得分中
    } // 结束所有行的积分累加循环

    return totalScore; // 返回最终计算出的最大总得分
} // 结束 matrixScore 函数

int main() { // 程序主入口函数
    // 提高 IO 效率
    ios::sync_with_stdio(false); // 取消 C++ 标准流与 C 语言标准输入输出流的同步，加速 cin/cout
    cin.tie(nullptr);            // 解绑 cin 与 cout 的绑定关系，避免每次 cin 前强制刷新输出缓冲区

    int m, n; // 声明矩阵行数 m 和列数 n
    if (cin >> m >> n) { // 从标准输入读取矩阵行数 m 和列数 n，成功读入后执行后续逻辑
        vector<vector<int>> grid(m, vector<int>(n)); // 初始化 m 行 n 列的二维动态数组 grid
        for (int i = 0; i < m; ++i) { // 嵌套循环外层：遍历每一行
            for (int j = 0; j < n; ++j) { // 嵌套循环内层：遍历每一列
                cin >> grid[i][j]; // 依次读入矩阵中的每个元素（0 或 1）
            } // 结束列读取
        } // 结束行读取

        cout << matrixScore(grid) << "\n"; // 调用 matrixScore 函数求解并输出最大得分，输出换行符
    } // 结束输入成功校验

    return 0; // 程序正常执行完成，向操作系统返回状态码 0
} // 结束 main 函数